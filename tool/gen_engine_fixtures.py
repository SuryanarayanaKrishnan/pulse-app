def gen_dictionary() -> None:
    lines = [
        "// GENERATED by tool/gen_engine_fixtures.py from pulse-api app/services/merchants.py.",
        "// Do not edit by hand: change the Python dictionary and regenerate.",
        "// ignore_for_file: lines_longer_than_80_chars",
        "",
        "import 'types.dart';",
        "",
        "/// (name, category slug, pattern, direction restriction)",
        "typedef RawMerchantEntry = (String, String, String, Direction?);",
        "",
        "const List<RawMerchantEntry> rawMerchantDictionary = [",
    ]
    for e in DICTIONARY:
        d = "null" if e.direction is None else f"Direction.{e.direction.value}"
        assert '"""' not in e.pattern.pattern and '"""' not in e.name
        lines.append(f'  (r"""{e.name}""", \'{e.category}\', r"""{e.pattern.pattern}""", {d}),')
    lines.append("];")
    (ROOT / "lib/core/engine/merchant_dictionary.dart").write_text("\n".join(lines) + "\n")


