def gen_rules() -> None:
    acc1, acc2 = "11111111-1111-4111-8111-111111111111", "22222222-2222-4222-8222-222222222222"

    def facts(**over):
        base = {
            "merchant_raw": "CARREFOUR MOE DUBAI AE", "merchant_normalized": "Carrefour", "notes": None,
            "amount_minor": 12_500, "direction": "debit", "account_id": acc1, "source": "sms",
        }
        return {**base, **over}

    def tf(f):
        return TxnFacts(
            f["merchant_raw"], f["merchant_normalized"], f["notes"], f["amount_minor"],
            Direction(f["direction"]) if f["direction"] else None,
            UUID(f["account_id"]) if f["account_id"] else None,
            TxnSource(f["source"]) if f["source"] else None,
        )

    m = lambda op, v, field="merchant": {"field": field, "op": op, "value": v}  # noqa: E731
    amt = lambda **k: {"field": "amount", **k}  # noqa: E731
    cases = [
        ([m("contains", "carre")], facts()),
        ([m("contains", "MOE DUBAI")], facts()),
        ([m("equals", "  carrefour ")], facts()),
        ([m("equals", "carre")], facts()),
        ([m("regex", r"^carre\w+$")], facts()),
        ([m("regex", r"^lulu")], facts()),
        ([m("contains", "birthday", "description")], facts(merchant_raw="POS 123 SOME SHOP", notes="birthday gift")),
        ([m("contains", "some shop", "description")], facts(merchant_raw="POS 123 SOME SHOP", notes="birthday gift")),
        ([m("equals", "BIRTHDAY GIFT", "description")], facts(merchant_raw="POS 123 SOME SHOP", notes="birthday gift")),
        ([m("contains", "x", "description")], facts(merchant_raw=None)),
        ([amt(op="equals", value_minor=5000)], facts(amount_minor=5000)),
        ([amt(op="equals", value_minor=5001)], facts(amount_minor=5000)),
        ([amt(op="between", min_minor=5000, max_minor=6000)], facts(amount_minor=5000)),
        ([amt(op="between", min_minor=5001, max_minor=6000)], facts(amount_minor=5000)),
        ([amt(op="gte", value_minor=5000)], facts(amount_minor=5000)),
        ([amt(op="lte", value_minor=4999)], facts(amount_minor=5000)),
        ([amt(op="gte", value_minor=1)], facts(amount_minor=None)),
        (
            [{"field": "direction", "value": "debit"}, {"field": "account", "account_id": acc1},
             {"field": "source", "value": "sms"}, m("contains", "carrefour")],
            facts(),
        ),
        ([{"field": "direction", "value": "debit"}, m("contains", "carrefour")], facts(direction="credit")),
        ([{"field": "account", "account_id": acc1}], facts(account_id=acc2)),
        ([{"field": "source", "value": "sms"}], facts(source="manual")),
        ([], facts()),
    ]
    out = [
        {"conditions": c, "facts": f, "matches": compile_rule(c).matches(tf(f))} for c, f in cases
    ]
    # priority semantics
    r_specs = [
        {"id": "a", "priority": 1, "conditions": [m("contains", "carre")], "category_id": "b", "tags": ["food"]},
        {"id": "b", "priority": 2, "conditions": [m("contains", "carre")], "category_id": "c",
         "rename_merchant": "Carrefour MOE", "tags": ["food", "weekly"]},
        {"id": "c", "priority": 3, "conditions": [m("contains", "nothing")], "category_id": "a"},
        {"id": "d", "priority": 4, "conditions": [m("contains", "carre")], "mark_transfer": True,
         "exclude_from_budget": True},
    ]

    def build(specs):
        return [
            compile_rule(
                s["conditions"], id=s["id"], priority=s["priority"], category_id=s.get("category_id"),
                rename_merchant=s.get("rename_merchant"), mark_transfer=s.get("mark_transfer", False),
                exclude_from_budget=s.get("exclude_from_budget", False), tags=s.get("tags", []),
            )
            for s in specs
        ]

    def outcome(o):
        return None if o is None else {
            "category_id": o.category_id, "rename_merchant": o.rename_merchant, "mark_transfer": o.mark_transfer,
            "exclude_from_budget": o.exclude_from_budget, "tags": o.tags, "rule_ids": o.rule_ids,
            "first_rule_id": o.first_rule_id,
        }

    evals = []
    for subset in ([0, 1, 2], [2], [0, 3], [1, 2, 3]):
        specs = [r_specs[i] for i in subset]
        evals.append({"rules": specs, "facts": facts(), "outcome": outcome(evaluate(build(specs), tf(facts())))})
    dump("rules.json", {"conditions": out, "evaluations": evals})


