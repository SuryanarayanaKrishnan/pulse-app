def gen_catalog() -> None:
    spec = importlib.util.spec_from_file_location(
        "m0004", next((API / "alembic/versions").glob("*_0004_*.py"))
    )
    assert spec and spec.loader
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    cards = []
    for c in mod.UAE_CARDS:
        issuer_slug = "".join(ch if ch.isalnum() else "-" for ch in c["issuer"].lower()).strip("-")
        name_slug = "".join(ch if ch.isalnum() else "-" for ch in c["name"].lower()).strip("-")
        structure = {k: v for k, v in c["reward_structure"].items() if k != "url"}
        cards.append(
            {
                "id": f"{issuer_slug}-{name_slug}",
                "issuer": c["issuer"],
                "name": c["name"],
                "network": c["network"],
                "annual_fee_minor": c["annual_fee_minor"],
                "min_salary_minor": c["min_salary_minor"],
                "reward_structure": structure,
                "perks": {},
                # Honest status: the seeded figures were written from memory of public product pages
                # and have NOT been checked against the issuers' current terms.
                "verified_on": None,
                "source": None,
            }
        )
    catalog = {
        "version": 1,
        "updated_on": "2026-11-26",
        "notice": "Illustrative figures taken from memory of public product pages. verified_on is null until a "
        "card has been checked against the issuer's published terms (then source holds the URL).",
        "cards": cards,
    }
    (ROOT / "assets/catalog/cards.json").write_text(json.dumps(catalog, indent=1, ensure_ascii=False) + "\n")


